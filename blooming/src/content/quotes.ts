  '每天一小步，就已經很好。',
  '身體正在努力，你也是。',
  '好好休息，也是一種前進。',
  '讓今天溫柔一點。',
  '相信屬於你的時間。',
  '吃好、呼吸、慢慢綻放。',
  '你已經足夠好了。',
  '每個季節，都有它的花。',
  '安穩的心，會長出美好的東西。',
  '對鏡子裡的自己溫柔一點。',
  '喜悅藏在每天的小儀式裡。',
